// Generates app/dark.css: a prefers-color-scheme:dark twin of every color declaration in the site stylesheets.
// Lightness is inverted (hue kept) so surfaces go dark and text goes light; boards and tiles are left untouched.
// Run: node scripts/build-dark-theme.mjs
import {readFileSync,writeFileSync} from 'node:fs';
const SOURCES=['app/globals.css','app/study.css','app/play.css'];
const SKIP_SELECTOR=/tile|game-board|board-slots|mini-board|countdown|confetti|result-boards|rival-dock \.mini|\.dot-|recharts/;
const COLOR_PROPS=/^(--[\w-]+|color|background(-color)?|border(-(top|right|bottom|left))?(-color)?|outline(-color)?|fill|stroke|accent-color|text-decoration-color|caret-color)$/;
const NAMED={white:'#ffffff',black:'#000000'};

function hexToRgb(hex){let h=hex.slice(1);if(h.length<=4)h=[...h].map(c=>c+c).join('');return {r:parseInt(h.slice(0,2),16)/255,g:parseInt(h.slice(2,4),16)/255,b:parseInt(h.slice(4,6),16)/255,a:h.length===8?h.slice(6,8):''};}
function rgbToHsl({r,g,b}){const max=Math.max(r,g,b),min=Math.min(r,g,b),l=(max+min)/2;if(max===min)return {h:0,s:0,l};const d=max-min,s=l>.5?d/(2-max-min):d/(max+min);const h=max===r?(g-b)/d+(g<b?6:0):max===g?(b-r)/d+2:(r-g)/d+4;return {h:h/6,s,l};}
function hslToHex({h,s,l}){const f=n=>{const k=(n+h*12)%12,a=s*Math.min(l,1-l);return Math.round((l-a*Math.max(-1,Math.min(k-3,9-k,1)))*255).toString(16).padStart(2,'0');};return '#'+f(0)+f(8)+f(4);}
// Near-white surfaces become plum (the board hue) rather than muddy brown; pale tints keep their hue but lose saturation.
function invert(hex){const rgb=hexToRgb(hex),hsl=rgbToHsl(rgb);const l=.08+(1-hsl.l)*.88;
  const surface=hsl.l>.88,tint=hsl.l>.7&&!surface;
  return hslToHex({h:surface?.77:hsl.h,s:surface?.16:tint?hsl.s*.45:hsl.s,l})+rgb.a;}
const convert=value=>value.replace(/#[0-9a-fA-F]{3,8}\b/g,m=>[4,5,7,9].includes(m.length)?invert(m):m).replace(/\b(white|black)\b/g,m=>invert(NAMED[m]));

// Minimal CSS walker: returns [{conditions:[...@media preludes], selector, declarations}]
function rules(css){
  css=css.replace(/\/\*[\s\S]*?\*\//g,'');const out=[];
  (function walk(text,conditions){let i=0;while(i<text.length){const open=text.indexOf('{',i);if(open<0)break;const prelude=text.slice(i,open).trim();let depth=1,j=open+1;while(depth&&j<text.length){if(text[j]==='{')depth++;else if(text[j]==='}')depth--;j++;}const body=text.slice(open+1,j-1);
    if(prelude.startsWith('@media'))walk(body,[...conditions,prelude]);else if(!prelude.startsWith('@'))out.push({conditions,selector:prelude,body});i=j;}})(css,[]);
  return out;
}
let output='/* Generated by scripts/build-dark-theme.mjs; edit the source stylesheets and re-run instead of editing this file. */\n@media (prefers-color-scheme:dark){\n:root{color-scheme:dark}\n';
for(const file of SOURCES)for(const {conditions,selector,body} of rules(readFileSync(file,'utf8'))){
  if(SKIP_SELECTOR.test(selector)||conditions.some(c=>/prefers-reduced-motion|prefers-color-scheme/.test(c)))continue;
  const decls=body.split(';').map(d=>d.trim()).filter(Boolean).flatMap(d=>{const k=d.indexOf(':');const prop=d.slice(0,k).trim(),value=d.slice(k+1).trim();if(!COLOR_PROPS.test(prop)||prop==='color-scheme')return [];const next=convert(value);return next===value?[]:[`${prop}:${next}`];});
  if(!decls.length)continue;
  const rule=`${selector}{${decls.join(';')}}`;
  output+=conditions.reduceRight((inner,c)=>`${c}{${inner}}`,rule)+'\n';
}
// Hand-tuned: policy colors are used as text, so lift them for contrast on dark surfaces.
output+=`.lab-player-name h2,.thinking-dots,.decision-dial{color:color-mix(in srgb,var(--policy-color) 55%,#fff)}
.decision-dial{background:color-mix(in srgb,var(--policy-color) 22%,#1b1622);border-color:color-mix(in srgb,var(--policy-color) 45%,#1b1622)}
.decision-bars .chosen b{background:color-mix(in srgb,var(--policy-color) 70%,#fff)}
.tab-pill{background:#e9dcf5}.mode-row .tabs-trigger[data-state=active] .tab-label{color:#231b2b}
}\n`;
writeFileSync('app/dark.css',output);
console.log('wrote app/dark.css',output.length,'bytes');
